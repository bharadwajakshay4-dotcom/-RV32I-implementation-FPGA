-- Wrapper around the Vivado Block Memory Generator IP named "blk_ram".
--
-- Memory organization:
--   1024 words x 32 bits = 4 KiB
--   Port A: instruction read only
--   Port B: data read/write with four byte-write enables

library ieee;
use ieee.std_logic_1164.all;

library work;
use work.rv32i_pkg.all;

entity unified_bram is
    port (
        clk_i : in std_logic;

        instruction_addr_i : in  bram_addr_t;
        instruction_data_o : out word_t;

        data_addr_i       : in  bram_addr_t;
        data_write_data_i : in  word_t;
        data_wstrb_i      : in  byte_strobe_t;
        data_read_data_o  : out word_t
    );
end entity unified_bram;

architecture rtl of unified_bram is

    -- Component interface generated by the blk_mem_gen 8.4 IP. Component
    -- instantiation allows Vivado to bind its managed synthesis/simulation
    -- model to this wrapper.
    component blk_ram is
        port (
            clka  : in  std_logic;
            ena   : in  std_logic;
            wea   : in  std_logic_vector(3 downto 0);
            addra : in  std_logic_vector(9 downto 0);
            dina  : in  std_logic_vector(31 downto 0);
            douta : out std_logic_vector(31 downto 0);

            clkb  : in  std_logic;
            enb   : in  std_logic;
            web   : in  std_logic_vector(3 downto 0);
            addrb : in  std_logic_vector(9 downto 0);
            dinb  : in  std_logic_vector(31 downto 0);
            doutb : out std_logic_vector(31 downto 0)
        );
    end component blk_ram;

begin

    memory_inst : blk_ram
        port map (
            -- Port A is permanently enabled and cannot write.
            clka  => clk_i,
            ena   => '1',
            wea   => NO_BYTE_WRITE,
            addra => instruction_addr_i,
            dina  => ZERO_WORD,
            douta => instruction_data_o,

            -- Port B is permanently enabled. A zero data_wstrb_i performs a
            -- read only; asserted byte lanes perform a write.
            clkb  => clk_i,
            enb   => '1',
            web   => data_wstrb_i,
            addrb => data_addr_i,
            dinb  => data_write_data_i,
            doutb => data_read_data_o
        );

end architecture rtl;
